// oxlint-disable-next-line typescript/no-require-imports -- Playwright's existing test suite uses CommonJS.
const { test, expect } = require('@playwright/test');

test('two buyers can save, share, filter, revoke and delete durable purchase records', async ({ browser }, testInfo) => {
  const first = await browser.newContext();
  const second = await browser.newContext();
  const page = await first.newPage();
  const viewer = await second.newPage();
  const product = `UI SSD ${Date.now()}`;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/purchases.html');
  const entry = page.locator('[data-role=entry]');
  await entry.getByLabel('상품명', { exact: true }).fill(product);
  await entry.getByLabel('부품 종류').selectOption('storage');
  await entry.getByLabel('개당 구매 가격 (원)').fill('99000');
  await entry.getByLabel('수량', { exact: true }).fill('2');
  await entry.getByLabel('구매일 (한국 기준)').fill('2026-01-01');
  await entry.getByLabel('판매처 (선택)').fill('테스트 판매처');
  await expect(entry.locator('[name=shared]')).not.toBeChecked();
  await entry.getByRole('button', { name: '구매이력 저장' }).click();
  await expect(page.locator('[data-role=saved]')).toHaveText('구매이력을 서버에 저장했습니다.');
  await expect(page.locator('.ph-record').filter({ hasText: product })).toContainText('합계 198,000원');
  await page.reload();
  await page.getByRole('button', { name: '내 구매이력', exact: true }).click();
  const saved = page.locator('.ph-record').filter({ hasText: product });
  await expect(saved).toContainText('나만 보기');
  await viewer.goto('/purchases.html');
  await expect(viewer.locator('.ph-record').filter({ hasText: product })).toHaveCount(0);
  await saved.getByRole('button', { name: '다른 구매자에게 공유' }).click();
  await expect(saved).toContainText('공유 중');
  await viewer.getByRole('button', { name: '검색', exact: true }).click();
  await expect(viewer.locator('.ph-record').filter({ hasText: product })).toContainText('테스트 판매처');
  await viewer.locator('[data-role=filters] [name=query]').fill(product);
  await viewer.getByRole('button', { name: '검색', exact: true }).click();
  await expect(viewer.locator('.ph-record')).toHaveCount(1);
  await viewer.locator('.ph-record .ph-buyer').click();
  await expect(viewer.getByRole('button', { name: '전체 구매자 보기' })).toBeVisible();
  await viewer.getByRole('button', { name: '내 구매이력', exact: true }).click();
  await expect(viewer.locator('[data-role=status]')).toContainText('조건에 맞는 구매이력이 없습니다.');
  await page.screenshot({ path: testInfo.outputPath('history-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('history-mobile.png'), fullPage: true });
  await saved.getByRole('button', { name: '공유 중단' }).click();
  await expect(saved).toContainText('나만 보기');
  await viewer.getByRole('button', { name: '여러 사용자 구매이력', exact: true }).click();
  await expect(viewer.locator('.ph-record').filter({ hasText: product })).toHaveCount(0);
  page.once('dialog', dialog => dialog.accept());
  await saved.getByRole('button', { name: '삭제', exact: true }).click();
  await expect(saved).toHaveCount(0);
  expect(errors).toEqual([]);
  await first.close(); await second.close();
});
